class SqueezedCatTarget(TargetGenerator):
    """Generates squeezed Schrödinger cat state targets.

    The state is generated by applying a squeezing operator to a coherent cat state:
    :math:`\\hat{S}(r) \\mathcal{N}_p (|\\alpha\\rangle + (-1)^p |-\\alpha\\rangle)`.

    Args:
        alpha (float, optional): Coherent state amplitude :math:`\\alpha`. Defaults to 3.0.
        r (float, optional): Squeezing parameter :math:`r`. Defaults to 1.38.
        p (int, optional): Parity indicator (0 for even cat, 1 for odd cat). Defaults to 0.
    """

    def __init__(self, alpha=3.0, r=1.38, p=0):
        self.alpha = alpha
        self.r = r
        self.p = p

    def get_target_ket(self, cutoff_dim: int) -> np.ndarray:
        """Generates the squeezed cat target state vector.

        Args:
            cutoff_dim (int): The Fock space cutoff dimension.

        Returns:
            np.ndarray: The target state ket in the Fock basis.
        """
        print(f"Generating Squeezed Cat Target (alpha={self.alpha}, r={self.r}, p={self.p})...")

        prog = sf.Program(1)
        with prog.context as q:
            Catstate(a=self.alpha, p=self.p) | q[0]
            Sgate(r=self.r) | q[0]

        eng = sf.Engine("fock", backend_options={"cutoff_dim": cutoff_dim})
        state = eng.run(prog).state

        return state.ket()


